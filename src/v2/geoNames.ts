/** 归一化：去声调 + 小写，保证 'Rhône'/'rhone'、'Tromsø'/'tromso' 互相命中。 */
function norm(s: string): string {
  return s.normalize('NFD').replace(/[\u0300-\u036f]/g, '').trim().toLowerCase()
}

let index: Map<string, string> | null = null

/** 将英文名翻译成中文（找不到返回 null；忽略大小写与声调符号）。 */
export function toChineseName(en: string): string | null {
  if (!en) return null
  if (!index) {
    index = new Map()
    for (const k in ZH_NAMES) {
      const nk = norm(k)
      if (!index.has(nk)) index.set(nk, ZH_NAMES[k])
    }
  }
  return index.get(norm(en)) ?? null
}
